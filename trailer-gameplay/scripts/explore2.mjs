import { launch, GAME, ROOT, sleep } from './cdp.mjs';
import { join } from 'node:path';
const b = await launch({ seedFile: join(GAME, 'scratch/qa/seed_dossier_progress.json') });
await b.nav('/?speed=3');
const dump = async (tag) => { console.log('==', tag, JSON.stringify(await b.ev(`[...document.querySelectorAll('button')].filter(x=>x.offsetParent!==null).map(x=>(x.getAttribute('aria-label')||x.textContent).trim().replace(/\s+/g,' ').slice(0,36))`))); };
const stateXY = (id) => b.ev(`(() => { const gs=[...document.querySelectorAll('svg g.cursor-pointer')]; return gs.length })()`);
await b.ev(`__click('Mr. Macaroony',900)`); await b.ev(`__click('Open case file',2000)`);
await dump('live0'); await b.shot(join(ROOT,'out/ex_live0.png'));
console.log('state groups', await stateXY());
await b.ev(`(()=>{const gs=[...document.querySelectorAll('svg g.cursor-pointer')];const g=gs[Math.floor(gs.length/2)];const r=g.getBoundingClientRect();window.__p={x:r.left+r.width/2,y:r.top+r.height/2};})()`);
const p = await b.ev('window.__p'); console.log(p);
await b.tap(p.x, p.y); await sleep(1500);
await dump('planted'); await b.shot(join(ROOT,'out/ex_planted.png'));
await b.ev(`document.querySelector('button[aria-label^="Collect"]')?.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}))`); await sleep(1800);
await dump('popped'); await b.shot(join(ROOT,'out/ex_popped.png'));
await b.ev(`__click('Dismiss',900) || __click('Got it',900) || __click('Continue',900)`);
await sleep(800); await dump('after alert'); await b.shot(join(ROOT,'out/ex_afteralert.png'));
await b.ev(`__click('Channels',1500)`); await dump('channels'); await b.shot(join(ROOT,'out/ex_channels.png'));
b.close();
