// Builds docs/DIFFICULTY.md: the difficulty system in plain English, with the tables generated from the live game data and the
// latest plan matrix (scratch/strat_T*.log from `npm run strategies`), so it cannot drift.
//   npm run doc:difficulty
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { TARGETS, TIERS, targetsInTier, describeTarget, STYLE_TEXT, TEMPERAMENT_TEXT, FOLDER_INFO } from '../src/engine/data/targets';
import { BALANCE } from '../src/engine/balance';
import { RATING_RANGES } from '../src/engine/data/ratings';
import { FAMILY_HINT, FAMILY_NAME, playStyleOf, PLAY_STYLES } from '../src/engine/data/playStyles';
import { STRATEGIES } from '../src/engine/bots';
import { PLAN } from './difficultyPlan';

// Latest plan matrix: id -> win % per plan (same order as STRATEGIES)
const matrix: Record<string, number[]> = {};
const dScore: Record<string, number> = {};   // the difficulty score D (0 = trivial, 100 = impossible)
for (const t of TIERS) {
  const p = `scratch/strat_T${t}.log`;
  if (!existsSync(p)) continue;
  for (const line of readFileSync(p, 'utf8').split('\n')) {
    const m = line.match(/^\s+([a-z_0-9]+)\s+((?:\d+\s+){10})\|/);
    if (m) {
      matrix[m[1]] = m[2].trim().split(/\s+/).map(Number);
      const dm = line.match(/\|\s+D\s*(\d+)/);
      if (dm) dScore[m[1]] = Number(dm[1]);
    }
  }
}
const have = Object.keys(matrix).length > 0;
const mean = (a: number[]) => Math.round(a.reduce((x, y) => x + y, 0) / a.length);
const beaten = (id: string) => (matrix[id] ? STRATEGIES.filter((_, i) => matrix[id][i] >= 50).map(s => s.name) : []);

const tr = BALANCE.tier;
const tierName = (t: number) => FOLDER_INFO[t as 1].name;
const driver = (id: string) => {
  const t = TARGETS.find(x => x.id === id)!;
  const skip = new Set<string>([...Object.values(STYLE_TEXT), ...Object.values(TEMPERAMENT_TEXT)]);
  return describeTarget(t).filter(l => !skip.has(l) && !l.startsWith('Weak to') && !l.startsWith('Signature move')).join(' ');
};
const nice = (s: string) => s.replace('THE_', '').replace('_', ' ').toLowerCase().replace(/^./, c => c.toUpperCase());

const rows = (tier: number) => PLAN[tier].order.slice().reverse().map(id => {
  const t = TARGETS.find(x => x.id === id)!;
  const m = matrix[id];
  const ps = playStyleOf(t);
  return `| ${t.prRating} | **${t.shortName}** (${id}) | ${ps?.label ?? ''} | ${nice(t.ai.defenseStyle)} / ${nice(t.ai.temperament)} | ${dScore[id] ?? ''} | ${m ? `${mean(m)}%` : ''} | ${m ? `${Math.max(...m)}%` : ''} | ${beaten(id).join(', ')} | ${driver(id)} |`;
}).join('\n');

const range = (a: number[]) => (a.length ? `${Math.min(...a)} to ${Math.max(...a)}` : '');
const bands = TIERS.map(t => {
  const ids = PLAN[t].order.filter(id => matrix[id] && dScore[id] !== undefined);
  if (!ids.length) return '';
  return `| ${t} | ${tierName(t)} | ${PLAN[t].order.length} | ${range(ids.map(id => dScore[id]))} | ${range(ids.map(id => mean(matrix[id])))}% | ${range(ids.map(id => Math.max(...matrix[id])))}% | ${range(ids.map(id => beaten(id).length))} of ${STRATEGIES.length} |`;
}).join('\n');

// The ladder, checked against the measurements: do the tiers stay apart, and does the rating rise with the score inside a tier?
const ladder = (() => {
  if (!Object.keys(dScore).length) return '';
  const ds = (t: number) => PLAN[t].order.map(id => dScore[id]).filter(x => x !== undefined);
  const lines: string[] = [];
  for (const t of [1, 2, 3, 4]) {
    const hi = Math.max(...ds(t)), lo = Math.min(...ds(t + 1));
    const crossing = PLAN[t + 1].order.filter(id => dScore[id] <= hi).length + PLAN[t].order.filter(id => dScore[id] >= lo).length;
    lines.push(`- Tier ${t} hardest D ${hi}, Tier ${t + 1} easiest D ${lo}: ${hi < lo ? `apart by ${lo - hi}` : `touching (${hi - lo} point${hi - lo === 1 ? '' : 's'} of overlap)`}${crossing ? `; ${crossing} Target${crossing > 1 ? 's' : ''} within reach of the neighbouring tier` : ''}.`);
  }
  for (const t of TIERS) {
    const ids = PLAN[t].order, d = ids.map(id => dScore[id]);
    let inv = 0;
    for (let i = 1; i < ids.length; i++) if (d[i] < d[i - 1]) inv++;
    lines.push(`- Tier ${t}: rating order against difficulty score, ${ids.length - 1 - inv} of ${ids.length - 1} neighbouring pairs in the right order.`);
  }
  return lines.join('\n');
})();

const famCount = (f: string) => Object.entries(PLAY_STYLES).filter(([, w]) => w.some(([x]) => x === f)).length;

const doc = `# How difficulty works in I Heard A Rumor

*This file is generated by \`npm run doc:difficulty\` from the game's real numbers. Do not edit it by hand.*

## 1. What "difficulty" means

You win by getting **75% of Nigeria to believe the story** before the days run out. You can lose three ways:

| You lose when… | What it means |
|---|---|
| **Heat reaches 100%** | The security services raid you ("busted"). |
| **Cover-Up reaches 100%** | The Target's spin machine wins; the story is dead. |
| **The days run out** | The story goes stale before enough people believe it. |

A Target is not simply "harder" because a stronger player is needed. Targets are harder in two ways, and the game keeps them separate:

1. **They ask for a different plan.** Each Target puts one or two kinds of *pressure* on you. Every kind punishes some plans and rewards others, so the right plan for one Target is the wrong plan for the next.
2. **They allow fewer plans.** The higher the rating, the narrower the set of plans that beat it. Tier 1 lets nearly any sensible plan win; the top of Tier 5 is beaten by one or two precise plans, executed well.

Every Target can be beaten by at least one realistic plan (a decent human, collecting most sparks and reading the event cards). That is checked by simulation, not assumed.

## 2. The ladder (like Chess.com's bots)

The **PR Rating** (300 to 3300) is a single ladder. The tiers are just slices of it and they follow each other: the hardest Tier 1 Target is easier than the easiest Tier 2 Target, and so on up. Inside a tier a higher rating really is harder: the Targets are ordered by how hard they *measure* and the ratings are spread evenly along that order.

| Tier | Name | Rating range | Days | Heat speed | Their Cover-Up speed | Doubt growth | Extra starting Doubt |
|---|---|---|---|---|---|---|---|
${TIERS.map(t => `| ${t} | ${tierName(t)} | ${RATING_RANGES[t][0]} to ${RATING_RANGES[t][1]} | ${tr.days[t - 1]} | ×${tr.heat[t - 1]} | ×${tr.coverUp[t - 1]} | ×${tr.doubtGrowth[t - 1]} | +${tr.doubtAdd[t - 1]}% |`).join('\n')}

The Target's own settings (below) sit on top of these tier baselines.

**Stars** are about *your* skill on a win: 2 stars means winning within 75% of the days with peak Heat under 75%; 3 stars means within 60% of the days, peak Heat under 50%, and no exposed forgeries.

## 3. The four kinds of pressure

Each Target has one or two **play styles**. The dossier shows them as a hint ("Play style: Watched + Short memory") without spoiling the answer.

| Pressure | What it is | Hurts | Rewards |
|---|---|---|---|
${(['FORCE', 'SPIN', 'CLOCK', 'FAITH'] as const).map(f => `| **${FAMILY_NAME[f]}** (${famCount(f)} Targets) | ${FAMILY_HINT[f]} | ${{ FORCE: 'Loud, viral plans (Blitz, Wildfire, Forger)', SPIN: 'Plans that ignore Spin bubbles and Cover-Up', CLOCK: 'Slow, cautious plans (Quiet, Fortress)', FAITH: 'Viral plans with no evidence' }[f]} | ${{ FORCE: 'Quiet, Fortress', SPIN: 'Fortress, Quiet, with Proof as support', CLOCK: 'Exploit, Sprint', FAITH: 'Any plan that brings real evidence early' }[f]} |`).join('\n')}

Two pressures together make the Target narrow: for example **Watched + Short memory** needs a plan that is both quiet and fast, which most plans are not.

What each pressure changes in the numbers:
- **Watched**: your Heat builds faster; every counter-offensive adds Heat; the Target's Heat surges hit harder.
- **Spin machine**: their Cover-Up grows faster; their counter-stories and Spin bubbles are bigger.
- **Short memory**: the news cycle is shorter (fewer days), your story goes stale faster, distractions hit harder.
- **True believers**: every state starts with more Doubt, and Doubt builds faster.

### The plans we test against

These are ten plans a player could genuinely follow. The simulator plays each one, as a decent human, against every Target.

| Plan | What the player does |
|---|---|
${STRATEGIES.map(s => `| **${s.name}** | ${s.blurb} |`).join('\n')}

## 4. The other layers

On top of the tier baseline and the pressures, every Target has a character:
- **Defense style**: Iron Fist (your Heat +40%), Spin Doctor (+50% Spin bubbles, Heat −20%), Lawyer Up (longer, more frequent injunctions), Distractor (bigger distractions, faster staleness), Balanced.
- **Temperament**: when they hit back. Steady (counter-offensives at 20/45/70% belief), Crashout (rants early at 15%), Stoic (saves one ambush for 55%), Showman (more often, softer), Paranoid (your genuine evidence costs more Heat), Schemer (plants a bombshell at 30%).
- **Lanes**: weak to one channel lane (+25%), resists another (−25%).
- **Moves** (1 to 3 each): injunctions, distractions, Heat surges, counter-stories, bot swarms. Their strongest fires once at double strength at 50% belief.

And the settings the pressures turn (any Target can use any of them): Heat rate, counter-offensive Heat, Cover-Up rate, stale rate, starting Doubt (flat) and Doubt rate, Elite-city friction, forgery risk, Spin hubs, and the **days** adjustment (a short or long news cycle).

## 5. The tiers, as measured

${have ? `Every Target is played by every plan, as a decent human, on fresh random games. The **difficulty score D** (0 = trivial, 100 = impossible) is half "how many plans fail" and half "how hard is even the best plan". *Breadth* is the average win rate over the ten plans, *best plan* is the win rate of the plan that suits the Target most, and *plans that work* counts the plans that win at least half the time.

| Tier | Name | Targets | Difficulty D | Breadth | Best plan | Plans that work |
|---|---|---|---|---|---|---|
${bands}

The ladder, checked against those measurements:

${ladder}
` : 'Run `npm run strategies` to fill in the measured columns.'}
${TIERS.map(t => `- **Tier ${t}, ${tierName(t)}**: ${FOLDER_INFO[t as 1].blurb}`).join('\n')}

## 6. Every Target

Hardest first in each tier. *D* = difficulty score; *Breadth* = average win % over the ten plans; *Best* = win % of the best plan; *Plans that work* = plans winning at least 50%.

${TIERS.map(t => `### Tier ${t}: ${tierName(t)}\n\n| Rating | Target | Play style | Defense / temperament | D | Breadth | Best | Plans that work | Their numbers |\n|---|---|---|---|---|---|---|---|\n${rows(t)}\n`).join('\n')}
## 7. How to change a Target

- **Which pressures it has**: edit its line in \`src/engine/data/playStyles.ts\` (the weights say how much of each).
- **Where it sits**: edit the order in \`scripts/difficultyPlan.ts\` (easiest to hardest), then re-tune.
- **By hand**: edit its \`mods\` line and the numbers in its \`ab('KIND', every, start, strength, …)\` calls in \`src/engine/data/targets/tier*.ts\`; its style and temperament are in \`src/engine/data/aiProfiles.ts\`.
- **Re-tune**:
  \`\`\`
  node scripts/bake.mjs originals                       # start from the original numbers
  npx esbuild scripts/tune2.ts --bundle --platform=node --format=cjs --outfile=node_modules/.cache/tune2.cjs
  TIER=3 RUNS=12 node node_modules/.cache/tune2.cjs     # one tier per process; run the five in parallel
  TUNED=tuned2 node scripts/bake.mjs                    # write the tuned numbers into the Target files
  npm run rate                                          # ratings follow the plan order
  npm run strategies                                    # re-measure every plan against every Target
  npm run doc:difficulty                                # rebuild this file
  \`\`\`
- **Check nothing broke**: \`npm run verify\`.
`;

mkdirSync('docs', { recursive: true });
writeFileSync('docs/DIFFICULTY.md', doc);
console.log(`docs/DIFFICULTY.md (${doc.length} characters${have ? ', with the plan matrix' : ''})`);
