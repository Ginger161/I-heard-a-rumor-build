// Assigns PR Ratings from the difficulty plan (scripts/difficultyPlan.ts): each tier's Targets are listed easiest to hardest (the plan
// is re-ordered from measurements by scripts/reorderPlan.mjs), so the rating simply follows that order, evenly spread across the tier's range. The tuner and the plan matrix then check, by
// simulation, that the measured difficulty really follows this order (`npm run spread`, `npm run strategies`).
//   npm run rate
import { readFileSync, writeFileSync } from 'fs';
import { RATING_RANGES } from '../src/engine/data/ratings';
import { PLAN } from './difficultyPlan';

const generated: Record<string, number> = {};
for (const [tier, plan] of Object.entries(PLAN)) {
  const [lo, hi] = RATING_RANGES[Number(tier)];
  const n = plan.order.length;
  plan.order.forEach((id, i) => { generated[id] = Math.round((lo + ((hi - lo) * i) / Math.max(1, n - 1)) / 10) * 10; });
}

const path = 'src/engine/data/ratings.ts';
const marker = '// AUTO-GENERATED by `npm run rate`. Do not edit by hand.';
const src = readFileSync(path, 'utf8');
const head = src.slice(0, src.indexOf(marker));
const body = Object.keys(generated).sort().map(id => `  ${id}: ${generated[id]}`).join(',\n');
writeFileSync(path, `${head}${marker}\nexport const GENERATED_RATINGS: Record<string, number> = {\n${body}\n};\n`);

console.log('Ratings written for', Object.keys(generated).length, 'targets');
for (const [tier, plan] of Object.entries(PLAN)) console.log(`T${tier}: ` + plan.order.map(id => `${id}=${generated[id]}`).join('  '));
