// Calibrates PR Ratings from measured difficulty and writes them into src/engine/data/ratings.ts.
//   npm run rate               (RUNS=10 per target and skill by default)
// Within each folder, Targets are ranked by how often the expert and average bots beat them, then spread across
// the folder's rating range. Ratings fixed by the design doc (SPEC_RATINGS) are kept as written.
import { readFileSync, writeFileSync } from 'fs';
import { play, SKILLS } from './botLib';
import { TARGETS, TIERS, targetsInTier } from '../src/engine/data/targets';
import { RATING_RANGES, SPEC_RATINGS } from '../src/engine/data/ratings';

const RUNS = Number(process.env.RUNS ?? 10);
const use = SKILLS.filter(s => s.name !== 'sloppy');

const difficulty: Record<string, number> = {};
for (const t of TARGETS.filter(x => !x.packId)) {
  let score = 0;
  let n = 0;
  for (const skill of use) {
    let wins = 0, cover = 0, heat = 0;
    for (let i = 0; i < RUNS; i++) {
      const r = play(t.id, skill, 4000 + i * 977);
      if (r.status === 'WON') wins++;
      cover += r.coverUp;
      heat += r.heat;
    }
    // Lower win rate = harder; end-of-run pressure breaks ties between Targets that always win.
    score += (1 - wins / RUNS) * 100 + (cover / RUNS) * 0.3 + (heat / RUNS) * 0.2;
    n++;
  }
  difficulty[t.id] = score / n;
}

const generated: Record<string, number> = {};
for (const tier of TIERS) {
  const list = [...targetsInTier(tier)].sort((a, b) => difficulty[a.id] - difficulty[b.id]);
  const [lo, hi] = RATING_RANGES[tier];
  list.forEach((t, i) => {
    generated[t.id] = Math.round((lo + ((hi - lo) * i) / Math.max(1, list.length - 1)) / 10) * 10;
  });
}
// Spotlight creators use their tier's rating scale but have fixed spec ratings.
TARGETS.filter(t => !t.packId && t.folder === 'SPOTLIGHT').forEach(t => { generated[t.id] = SPEC_RATINGS[t.id] ?? 1000; });

const path = 'src/engine/data/ratings.ts';
const marker = '// AUTO-GENERATED by `npm run rate`. Do not edit by hand.';
const src = readFileSync(path, 'utf8');
const head = src.slice(0, src.indexOf(marker));
const body = Object.keys(generated).sort().map(id => `  ${id}: ${generated[id]}`).join(',\n');
writeFileSync(path, `${head}${marker}\nexport const GENERATED_RATINGS: Record<string, number> = {\n${body}\n};\n`);

console.log('Ratings written for', Object.keys(generated).length, 'targets');
TIERS.forEach(tier => {
  console.log(`T${tier}: ` + targetsInTier(tier).map(t => `${t.id}=${SPEC_RATINGS[t.id] ?? generated[t.id]}`).join('  '));
});
